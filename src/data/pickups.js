export function byCategory(cat) {
  if (!cat || cat === 'all') return PICKUPS
  if (CATEGORIES[cat]) return PICKUPS.filter(p => p.category === cat)
  // групповой фильтр ('Гитарные' / 'Басовые')
  return PICKUPS.filter(p => CATEGORIES[p.category].group === cat)
}
